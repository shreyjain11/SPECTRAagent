"""Fully execute the six corrected inline notebooks from the pinned public sources."""
from pathlib import Path
import ast,concurrent.futures,datetime,hashlib,json,os,platform,shutil,subprocess,sys,time
HERE=Path(__file__).resolve().parent;R=HERE.parents[2]
CACHE=Path('/private/tmp/am-opus-dependence-inputs-20261116')
WORK=Path('/private/tmp/am-opus-dependence-runs-20261116');WORK.mkdir(exist_ok=True)
PLAN=json.loads((HERE/'frozen-plan.json').read_text())
def sha(p):
 h=hashlib.sha256()
 with Path(p).open('rb') as f:
  for b in iter(lambda:f.read(8<<20),b''):h.update(b)
 return h.hexdigest()
def utc():return datetime.datetime.now(datetime.timezone.utc).isoformat()
def rel(p):return str(Path(p).relative_to(R))
books=sorted((R/'inline/alphamissense').glob('am-opus-r*/test-*.ipynb'))
n=json.loads(books[0].read_text());tree=ast.parse(''.join(n['cells'][2]['source']))
sources=next(ast.literal_eval(x.value) for x in tree.body if isinstance(x,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='SOURCES' for t in x.targets))
receipts=[]
for key,s in sources.items():
 p=CACHE/s['filename'];assert p.stat().st_size==s['bytes'] and sha(p)==s['sha256']
 receipts.append({'name':key,**s,'consumed_cache_path':str(p)})
(HERE/'public-source-inputs.json').write_text(json.dumps({'verified_at':utc(),'role':'Exact public raw files consumed by all full notebook executions','files':receipts},indent=2)+'\n')
def run(p):
 identifier=p.parent.name+'/'+p.stem;slug=identifier.replace('/','-');work=WORK/slug;work.mkdir(exist_ok=True)
 out=HERE/'outputs'/slug;out.mkdir(parents=True,exist_ok=True)
 before=sha(p);command=[sys.executable,str(HERE/'execute_notebook.py'),str(p),'--cwd',str(work),'--timeout','3600']
 env=dict(os.environ,AM_OPUS_INPUTS=str(CACHE),OPENBLAS_NUM_THREADS='1',OMP_NUM_THREADS='1',MKL_NUM_THREADS='1')
 start=utc();t=time.monotonic();print('START',identifier,start,flush=True)
 process=subprocess.run(command,env=env,text=True,capture_output=True)
 end=utc();elapsed=time.monotonic()-t
 (out/'execution.log').write_text('START '+start+'\nCOMMAND '+json.dumps(command)+'\n'+process.stdout+process.stderr+'\nEND '+end+'\n')
 if process.returncode:
  print('FAILED',identifier,process.stdout[-2500:],process.stderr[-2500:],flush=True)
  return None
 n=json.loads(p.read_text());indices=[i for i,c in enumerate(n['cells']) if c['cell_type']=='code']
 assert all(n['cells'][i]['execution_count'] is not None for i in indices)
 assert not any(o.get('output_type')=='error' for i in indices for o in n['cells'][i]['outputs'])
 generated=work/(slug+'-outputs')
 results=json.loads((generated/'CURRENT_RESULTS.json').read_text())
 assert results['cohort']=={'variants':273135,'assays':73,'proteins':64}
 # Keep small actual calculation tables, not six duplicate raw archives or full variant exports.
 for f in generated.iterdir():
  if f.suffix in {'.csv','.json'}:shutil.copyfile(f,out/f.name)
 (out/'execution-environment.json').write_text(json.dumps({'host':platform.node(),'python':sys.executable,'python_version':platform.python_version(),'started_at':start,'finished_at':end,'elapsed_seconds':elapsed,'working_directory':str(work),'input_cache':str(CACHE),'prepared_notebook_sha256':before,'executed_notebook_sha256':sha(p),'mode':'full_notebook','executed_notebook_cells':indices},indent=2)+'\n')
 statistical=['assay_performance.csv'] if p.stem=='test-02' else ['assay_level_scores.csv']
 statistical += [f.name for f in out.glob('control_cells_*.csv')]
 inputs=[{'path':rel(HERE/'public-source-inputs.json'),'role':'Checksum-verified manifest of the four public raw downloads actually consumed; raw files remain independently downloadable from their pinned URLs'}]
 inputs += [{'path':rel(out/name),'role':'Derived assay or within-assay bin records generated by this full execution and consumed by the protein-aware uncertainty calculation'} for name in statistical]
 registration={'analysis_id':identifier,'mode':'full_notebook','executed_notebook_cells':indices,
  'summary':'Reexecuted the complete corrected-score analysis with protein-aware uncertainty; assay-weighted estimates, fixed levels and the 273,135-variant cohort are retained.',
  'dependency_scope':'Every visible code cell was executed from four checksum-pinned public raw sources, including the official corrected-position AlphaMissense score join. No fresh model inference or audit-specific fine-tuning. Protein clustering changes uncertainty and its interpretation; reconstructed partitions remain within the original fixed panel.',
  'execution':{'host':platform.node(),'python':platform.python_version(),'elapsed_seconds':elapsed,'started_at':start,'finished_at':end,'command':' '.join(command),'driver':rel(HERE/'execute_notebook.py'),'log':rel(out/'execution.log'),'engine':'nbclient'},
  'inputs':inputs,'output_artifacts':[rel(f) for f in sorted(out.iterdir()) if f.is_file()]}
 (out/'registration.json').write_text(json.dumps(registration,indent=2)+'\n')
 print('DONE',identifier,'seconds',round(elapsed,1),'cells',len(indices),flush=True)
 return registration,results
collected=[]
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
 for result in pool.map(run,books):
  if result:collected.append(result)
(HERE/'registration.json').write_text(json.dumps([r for r,_ in collected],indent=2)+'\n')
(HERE/'current_results.json').write_text(json.dumps({r['analysis_id']:v for r,v in collected},indent=2)+'\n')
assert len(collected)==6,'Some full executions did not finish; see retained logs'
print('All six complete notebook executions finished.',flush=True)
